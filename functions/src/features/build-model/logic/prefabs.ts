/** 場所の種類に合う、部品の模型。知らない種類は「街歩き」の模型にする */
export function prefabFor(category: PinCategory): ModelJson {
  const parts = PREFABS[category] ?? PREFABS.town
  // 呼ぶ側が書き換えても元が変わらないよう、写しを返す
  return { version: MODEL_VERSION, parts: structuredClone(parts) }
}
