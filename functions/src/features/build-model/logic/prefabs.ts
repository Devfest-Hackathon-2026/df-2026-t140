// 用意した部品の模型。場所の種類ごとに 1 つ。
//
// - 今夜の「建築」は、ここから種類に合うものを選ぶ（Gemini の固定の応答）。AI が作ったものではない
// - 本物の Argon をつないだあとも、作れなかったとき・形が違ったときの代わりに使う（企画書「生成の失敗」）
// - 形は、このリポジトリで決めた数字を並べたもの。外の 3D モデルや画像は使っていない
// - 模型の決まり（原点は地面の真ん中、y が上、幅と奥行き 12・高さ 16 の箱の中）は domain/model3d.ts

function part(shape: ModelShape, size: Vec3, position: Vec3, color: string, extra: Partial<ModelPart> = {}): ModelPart {
  return { shape, size, position, color, ...extra }
}

