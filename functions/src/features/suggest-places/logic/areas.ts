// 位置は都道府県のおよその真ん中で、このリポジトリで書いたもの。

export interface Prefecture {
  /** 「長野県」 */
  name: string
  /** 文の中で探す言葉（「長野」） */
  short: string
  lat: number
  lng: number
}

const row = (name: string, lat: number, lng: number): Prefecture => ({
  name,
  short: name === '北海道' ? name : name.slice(0, -1),
  lat,
  lng,
})

