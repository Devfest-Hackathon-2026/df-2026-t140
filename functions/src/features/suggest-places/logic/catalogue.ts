// 見本の場所の一覧。固定の応答（GEMINI_PROVIDER=stub）のときに、ここから候補を選ぶ。
//
// - 日本のよく知られた場所を、種類ごとに並べた。名前、説明、およその位置は、このリポジトリで書いたもの。
//   Google Maps など地図サービスから取った内容ではない（Maps 由来の内容を Gemini や 3D 生成に渡さないため）
// - 位置はおよその緯度経度で、ピンを地図に置くためだけに使う。正確な場所や営業の情報ではない
// - 並び順は、その種類の中でよく知られている順。同じ条件なら前のものが先に選ばれる
// - 本物の Gemini（agy、vertex）をつないだら、この一覧は使われなくなる

export interface CatalogueEntry {
  name: string
  /** 都道府県（「長野県」） */
  pref: string
  /** 市町村（「安曇野市」） */
  city: string
  category: PinCategory
  /** 40 文字までの一言 */
  description: string
  lat: number
  lng: number
  /** 名前のほかに、この場所に当たる言葉（「わさび」「星空」など） */
  tags?: string[]
}

type Row = [name: string, pref: string, city: string, description: string, lat: number, lng: number, tags?: string[]]

function entries(category: PinCategory, rows: Row[]): CatalogueEntry[] {
  return rows.map(([name, pref, city, description, lat, lng, tags]) => ({
    name,
    pref,
    city,
    category,
    description,
    lat,
    lng,
    tags,
  }))
}

